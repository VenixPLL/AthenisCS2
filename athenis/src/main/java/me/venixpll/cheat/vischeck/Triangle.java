package me.venixpll.cheat.vischeck;

public class Triangle {
    public int a;
    public int b;
    public int c;

    public Triangle() {
        this.a = 0;
        this.b = 0;
        this.c = 0;
    }

    public Triangle(int a, int b, int c) {
        this.a = a;
        this.b = b;
        this.c = c;
    }
}
